-- Neon Barrage public leaderboard.
--
-- The browser only needs to read rankings and submit a name/score pair. The
-- identity and timestamp stay server-controlled, while the CHECK constraints
-- remain the final validation boundary even if a client is bypassed.

create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  player_name text not null,
  score integer not null,
  created_at timestamptz not null default now(),
  constraint leaderboard_player_name_length
    check (char_length(player_name) between 1 and 16),
  constraint leaderboard_player_name_trimmed
    check (player_name = btrim(player_name)),
  constraint leaderboard_player_name_no_control_chars
    check (player_name !~ '[[:cntrl:]]'),
  constraint leaderboard_score_plausible
    check (score >= 0 and score <= 1000000000)
);

comment on table public.leaderboard is
  'Neon Barrage scores; public clients may read rows and insert validated submissions.';
comment on column public.leaderboard.player_name is
  'Display name, one to sixteen characters, without surrounding whitespace or control characters.';
comment on column public.leaderboard.score is
  'Non-negative arcade score capped at one billion.';

create index if not exists leaderboard_score_created_at_id_idx
  on public.leaderboard (score desc, created_at asc, id asc);

-- RLS is enabled for the only table exposed through the public API.
alter table public.leaderboard enable row level security;

-- Start from no public table/sequence privileges. Explicit column grants below
-- prevent clients from supplying the identity or created_at values.
revoke all on table public.leaderboard from public, anon, authenticated;
revoke all on sequence public.leaderboard_id_seq from public, anon, authenticated;

grant select on table public.leaderboard to anon, authenticated;
grant insert (player_name, score) on table public.leaderboard to anon, authenticated;
grant usage, select on sequence public.leaderboard_id_seq to anon, authenticated;

drop policy if exists leaderboard_public_read on public.leaderboard;
create policy leaderboard_public_read
  on public.leaderboard
  for select
  to anon, authenticated
  using (true);

drop policy if exists leaderboard_public_insert on public.leaderboard;
create policy leaderboard_public_insert
  on public.leaderboard
  for insert
  to anon, authenticated
  with check (true);
