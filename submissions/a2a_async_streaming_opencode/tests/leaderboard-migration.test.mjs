import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import assert from 'node:assert/strict';

const migrationPath = new URL(
  '../supabase/migrations/20260807000000_create_leaderboard.sql',
  import.meta.url,
);
const migration = await readFile(migrationPath, 'utf8');
const sql = migration
  .replace(/--[^\n]*/g, ' ')
  .replace(/\s+/g, ' ')
  .trim()
  .toLowerCase();

test('migration defines the leaderboard data contract', () => {
  assert.match(sql, /create table if not exists public\.leaderboard/);
  assert.match(sql, /id bigint generated by default as identity primary key/);
  assert.match(sql, /player_name text not null/);
  assert.match(sql, /score integer not null/);
  assert.match(sql, /created_at timestamptz not null default/);
  assert.match(sql, /created_at timestamptz not null default now\(\)/);
  assert.match(sql, /char_length\(player_name\) between 1 and 16/);
  assert.match(sql, /player_name = btrim\(player_name\)/);
  assert.match(sql, /player_name !~ '\[\[:cntrl:\]\]+'/);
  assert.match(sql, /score >= 0 and score <= 1000000000/);
});

test('migration enables RLS and grants only public read/insert operations', () => {
  assert.match(sql, /alter table public\.leaderboard enable row level security/);
  assert.match(sql, /grant select on table public\.leaderboard to anon, authenticated/);
  assert.match(
    sql,
    /grant insert \(player_name, score\) on table public\.leaderboard to anon, authenticated/,
  );
  assert.match(sql, /grant usage, select on sequence public\.leaderboard_id_seq to anon, authenticated/);
  assert.match(sql, /create policy leaderboard_public_read[\s\S]*?for select[\s\S]*?to anon, authenticated[\s\S]*?using \(true\)/);
  assert.match(sql, /create policy leaderboard_public_insert[\s\S]*?for insert[\s\S]*?to anon, authenticated[\s\S]*?with check \(true\)/);
  assert.doesNotMatch(sql, /create policy[^;]+for (update|delete)/);
  assert.doesNotMatch(sql, /grant (update|delete|truncate|references|trigger)/);
});

test('client inserts cannot write server-owned columns', () => {
  const insertGrant = sql.match(
    /grant insert \(([^)]+)\) on table public\.leaderboard to anon, authenticated/,
  );

  assert.ok(insertGrant, 'an explicit column-level insert grant is required');
  assert.deepEqual(
    insertGrant[1].split(',').map((column) => column.trim()),
    ['player_name', 'score'],
  );
  assert.match(sql, /revoke all on table public\.leaderboard from public, anon, authenticated/);
  assert.match(sql, /revoke all on sequence public\.leaderboard_id_seq from public, anon, authenticated/);
});

test('migration does not contain credential material', () => {
  assert.doesNotMatch(migration, /service[_-]?role/i);
  assert.doesNotMatch(migration, /supabase_secret/i);
  assert.doesNotMatch(migration, /eyj[a-z0-9_-]+\.[a-z0-9_-]+\.[a-z0-9_-]+/i);
});
