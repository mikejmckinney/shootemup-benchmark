-- Neon Barrage public leaderboard. The anon role can only read and append valid scores.
create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  name text not null,
  score integer not null,
  created_at timestamptz not null default timezone('utc', now()),
  constraint leaderboard_name_valid check (
    char_length(btrim(name)) between 1 and 16
    and name !~ '[[:cntrl:]]'
  ),
  constraint leaderboard_score_valid check (score between 0 and 1000000000)
);

create index if not exists leaderboard_score_order
  on public.leaderboard (score desc, created_at asc);

alter table public.leaderboard enable row level security;

drop policy if exists "Public can read leaderboard" on public.leaderboard;
create policy "Public can read leaderboard"
  on public.leaderboard
  for select
  to anon
  using (true);

drop policy if exists "Public can submit valid scores" on public.leaderboard;
create policy "Public can submit valid scores"
  on public.leaderboard
  for insert
  to anon
  with check (
    char_length(btrim(name)) between 1 and 16
    and name !~ '[[:cntrl:]]'
    and score between 0 and 1000000000
  );

revoke all on table public.leaderboard from public;
grant select, insert on table public.leaderboard to anon;
revoke all on sequence public.leaderboard_id_seq from public;
grant usage, select on sequence public.leaderboard_id_seq to anon;
