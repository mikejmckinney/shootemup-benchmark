-- Neon Barrage public leaderboard. Apply through Supabase SQL editor or database API.
create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  name text not null,
  score integer not null,
  created_at timestamptz not null default timezone('utc'::text, now()),
  constraint leaderboard_name_valid check (char_length(name) between 1 and 16 and name ~ '^[A-Za-z0-9 _.-]+$'),
  constraint leaderboard_score_valid check (score between 0 and 999999999)
);

create index if not exists leaderboard_score_idx on public.leaderboard (score desc, created_at asc);

alter table public.leaderboard enable row level security;
revoke all on table public.leaderboard from public;
grant select on table public.leaderboard to anon, authenticated;
revoke insert on table public.leaderboard from anon, authenticated;
grant insert (name, score) on table public.leaderboard to anon, authenticated;
grant usage, select on sequence public.leaderboard_id_seq to anon, authenticated;

drop policy if exists "Anyone can read leaderboard" on public.leaderboard;
create policy "Anyone can read leaderboard" on public.leaderboard for select to anon, authenticated using (true);

drop policy if exists "Anyone can submit valid scores" on public.leaderboard;
create policy "Anyone can submit valid scores" on public.leaderboard for insert to anon, authenticated with check (
  char_length(name) between 1 and 16
  and name ~ '^[A-Za-z0-9 _.-]+$'
  and score between 0 and 999999999
);
