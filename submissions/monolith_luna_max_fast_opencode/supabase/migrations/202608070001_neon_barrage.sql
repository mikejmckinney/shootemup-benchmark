-- Neon Barrage public leaderboard. Apply this migration to the new project.
create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  name text not null,
  score integer not null,
  created_at timestamptz not null default timezone('utc', now()),
  constraint leaderboard_name_length check (char_length(name) between 1 and 16),
  constraint leaderboard_name_trimmed check (name = btrim(name)),
  constraint leaderboard_score_plausible check (score between 0 and 1000000000)
);

alter table public.leaderboard enable row level security;

drop policy if exists "Public can read leaderboard" on public.leaderboard;
create policy "Public can read leaderboard"
  on public.leaderboard
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Public can submit plausible scores" on public.leaderboard;
create policy "Public can submit plausible scores"
  on public.leaderboard
  for insert
  to anon, authenticated
  with check (
    char_length(name) between 1 and 16
    and name = btrim(name)
    and score between 0 and 1000000000
  );

revoke all on table public.leaderboard from public;
grant select, insert on table public.leaderboard to anon, authenticated;
grant usage, select on sequence public.leaderboard_id_seq to anon, authenticated;
