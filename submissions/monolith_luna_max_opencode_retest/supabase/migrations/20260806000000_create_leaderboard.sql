create table if not exists public.leaderboard_entries (
  id bigint generated by default as identity primary key,
  player_name text not null,
  score integer not null,
  created_at timestamptz not null default timezone('utc', now()),
  constraint leaderboard_player_name_length check (char_length(player_name) between 1 and 16),
  constraint leaderboard_player_name_format check (player_name ~ '^[A-Za-z0-9 _-]+$'),
  constraint leaderboard_score_plausible check (score >= 0 and score <= 2147483647)
);

create index if not exists leaderboard_entries_score_idx
  on public.leaderboard_entries (score desc, created_at asc);

alter table public.leaderboard_entries enable row level security;

revoke all on table public.leaderboard_entries from anon;
grant select on table public.leaderboard_entries to anon;
grant insert (player_name, score) on table public.leaderboard_entries to anon;
grant usage, select on sequence public.leaderboard_entries_id_seq to anon;

drop policy if exists "Public can read leaderboard" on public.leaderboard_entries;
create policy "Public can read leaderboard"
  on public.leaderboard_entries
  for select
  to anon
  using (true);

drop policy if exists "Public can submit plausible scores" on public.leaderboard_entries;
create policy "Public can submit plausible scores"
  on public.leaderboard_entries
  for insert
  to anon
  with check (
    char_length(player_name) between 1 and 16
    and player_name ~ '^[A-Za-z0-9 _-]+$'
    and score >= 0
    and score <= 2147483647
  );
