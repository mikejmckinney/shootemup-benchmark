-- Neon Barrage public leaderboard.
-- The table is intentionally tiny and anonymous: there is no account or
-- profile data to expose, and the public client only needs read + insert.

create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  player_name text not null,
  score integer not null,
  created_at timestamptz not null default timezone('utc', now()),
  constraint leaderboard_player_name_valid check (
    player_name = btrim(player_name)
    and char_length(player_name) between 1 and 16
    and player_name !~ '[[:cntrl:]]'
  ),
  constraint leaderboard_score_valid check (score between 0 and 2147483647)
);

create index if not exists leaderboard_score_created_idx
  on public.leaderboard (score desc, created_at asc);

alter table public.leaderboard enable row level security;

drop policy if exists "Anyone can read leaderboard" on public.leaderboard;
create policy "Anyone can read leaderboard"
  on public.leaderboard
  for select
  to anon, authenticated
  using (true);

drop policy if exists "Anyone can submit plausible scores" on public.leaderboard;
create policy "Anyone can submit plausible scores"
  on public.leaderboard
  for insert
  to anon, authenticated
  with check (
    player_name = btrim(player_name)
    and char_length(player_name) between 1 and 16
    and player_name !~ '[[:cntrl:]]'
    and score between 0 and 2147483647
  );

revoke all on table public.leaderboard from anon, authenticated;
grant select, insert on table public.leaderboard to anon, authenticated;

comment on table public.leaderboard is 'Anonymous Neon Barrage scores; public clients may only read or insert validated rows.';
