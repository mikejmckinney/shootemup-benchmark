create table if not exists public.scores (
  id bigint generated by default as identity primary key,
  player_name text not null,
  score integer not null,
  created_at timestamptz not null default now(),
  constraint scores_player_name_valid check (player_name ~ '^[A-Za-z0-9 _-]{1,16}$'),
  constraint scores_value_valid check (score >= 0 and score <= 2147483647)
);

alter table public.scores enable row level security;

drop policy if exists "Public can read scores" on public.scores;
create policy "Public can read scores" on public.scores for select to anon using (true);

drop policy if exists "Public can submit valid scores" on public.scores;
create policy "Public can submit valid scores" on public.scores for insert to anon with check (
  player_name ~ '^[A-Za-z0-9 _-]{1,16}$' and score >= 0 and score <= 2147483647
);

revoke all on table public.scores from public;
grant select, insert on table public.scores to anon;
grant usage, select on sequence public.scores_id_seq to anon;
