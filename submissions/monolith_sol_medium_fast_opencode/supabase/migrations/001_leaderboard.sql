create table public.leaderboard (
  id bigint generated by default as identity primary key,
  player_name text not null,
  score integer not null,
  created_at timestamptz not null default now(),
  constraint leaderboard_name_valid check (
    char_length(btrim(player_name)) between 1 and 16
    and player_name = btrim(player_name)
    and player_name ~ '^[A-Za-z0-9 _-]+$'
  ),
  constraint leaderboard_score_plausible check (score between 0 and 10000000)
);

alter table public.leaderboard enable row level security;

create policy "public can read leaderboard"
on public.leaderboard for select
to anon
using (true);

create policy "public can submit leaderboard scores"
on public.leaderboard for insert
to anon
with check (
  char_length(btrim(player_name)) between 1 and 16
  and player_name = btrim(player_name)
  and player_name ~ '^[A-Za-z0-9 _-]+$'
  and score between 0 and 10000000
);

grant select (id, player_name, score, created_at) on public.leaderboard to anon;
grant insert (player_name, score) on public.leaderboard to anon;
grant usage, select on sequence public.leaderboard_id_seq to anon;

create index leaderboard_score_rank_idx
on public.leaderboard (score desc, created_at asc);
